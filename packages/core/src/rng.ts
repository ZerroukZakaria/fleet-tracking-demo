/**
 * Small seeded pseudo-random generator (mulberry32).
 * Returns a function that yields numbers in [0, 1); the same seed always
 * produces the same sequence, which keeps simulations and tests reproducible.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}